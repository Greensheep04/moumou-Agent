"""Persistence ports.

The orchestrator talks to these protocols only. Production implementations live
in ``moumou.store`` (owned by P3); the SQLite reference lives in
``moumou.orchestrator.state``.
"""

from __future__ import annotations

from typing import Protocol, runtime_checkable

from .memory import MemoryRecord
from .task import TaskNode, TaskStatus
from .trace import TraceEvent


@runtime_checkable
class TaskRepo(Protocol):
    def add(self, node: TaskNode) -> None: ...
    def get(self, task_id: str) -> TaskNode | None: ...
    def children(self, task_id: str) -> list[TaskNode]: ...
    def by_status(self, status: TaskStatus) -> list[TaskNode]: ...
    def ready(self, limit: int = 1) -> list[TaskNode]: ...
    def promote(self) -> int:
        """Move dep-satisfied PENDING tasks to READY; kill orphans. Returns count."""
        ...

    def transition(self, task_id: str, to: TaskStatus, reason: str) -> None:
        """Validate and persist one state change plus its audit event.

        Implementations MUST make the update and the event insert atomic.
        """
        ...

    def set_deps(self, task_id: str, deps: list[str]) -> None: ...
    def set_result(self, task_id: str, result: str) -> None: ...
    def add_artifacts(self, task_id: str, artifacts: list[str]) -> None: ...
    def bump_retries(self, task_id: str) -> int: ...
    def event_log(self, task_id: str) -> list[dict]: ...


@runtime_checkable
class TraceStore(Protocol):
    def append(self, e: TraceEvent) -> None: ...
    def query(self, task_id: str) -> list[TraceEvent]: ...   # ascending by t0


@runtime_checkable
class MemoryStore(Protocol):
    def write(self, rec: MemoryRecord) -> str: ...
    def search(self, scope: str, query: str, k: int = 5) -> list[MemoryRecord]: ...
    def all(self, scope: str) -> list[MemoryRecord]: ...
    def update_score(self, rec_id: str, delta: float, used: bool = True) -> None: ...
    def evict_candidates(self, scope: str, threshold: float = 0.3) -> list[str]: ...
    def mark_deleted(self, rec_ids: list[str]) -> None: ...
